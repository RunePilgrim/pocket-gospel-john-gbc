# ---------------------------------------------------------------------------
# 2bpp conversion
# ---------------------------------------------------------------------------

def row_to_2bpp(row_str):
    """Convert an 8-character row string to (lo_byte, hi_byte)."""
    lo = 0
    hi = 0
    for i, ch in enumerate(row_str):
        bit = 7 - i
        if ch == '#':
            lo |= (1 << bit)
        elif ch != '.':
            raise ValueError(f"Invalid pixel char '{ch}' in row: {row_str}")
    return lo, hi


def glyph_to_bytes(rows):
    """Convert 8-row glyph definition to 16 bytes of 2bpp tile data."""
    result = []
    for row_str in rows:
        lo, hi = row_to_2bpp(row_str)
        result.append(lo)
        result.append(hi)
    return result


# ---------------------------------------------------------------------------
# Validation
# ---------------------------------------------------------------------------

def validate_glyphs():
    """Check all 96 glyphs are defined and well-formed."""
    for code in range(32, 128):
        if code not in GLYPHS:
            raise ValueError(f"Missing glyph for ASCII {code} ({chr(code)!r})")
        rows = GLYPHS[code]
        if len(rows) != 8:
            raise ValueError(
                f"ASCII {code} ({chr(code)!r}): expected 8 rows, got {len(rows)}"
            )
        for r, row_str in enumerate(rows):
            if len(row_str) != 8:
                raise ValueError(
                    f"ASCII {code} ({chr(code)!r}) row {r}: "
                    f"expected 8 chars, got {len(row_str)}"
                )
            for ch in row_str:
                if ch not in '.#':
                    raise ValueError(
                        f"ASCII {code} ({chr(code)!r}) row {r}: "
                        f"invalid char '{ch}'"
                    )


